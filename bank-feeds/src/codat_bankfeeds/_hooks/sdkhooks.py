"""SDKHooks registry — mirrors Speakeasy's _hooks/sdkhooks.py.

Generated by pipeline/postprocess_generated.py — do not edit by hand.
"""

from typing import Any, List, Optional, Tuple

from .registration import init_hooks
from .types import (
    AfterErrorContext,
    AfterErrorHook,
    AfterSuccessContext,
    AfterSuccessHook,
    BeforeRequestContext,
    BeforeRequestHook,
    HookContext,
    Hooks,
    SDKInitHook,
)


class SDKHooks(Hooks):
    def __init__(self) -> None:
        self.sdk_init_hooks: List[SDKInitHook] = []
        self.before_request_hooks: List[BeforeRequestHook] = []
        self.after_success_hooks: List[AfterSuccessHook] = []
        self.after_error_hooks: List[AfterErrorHook] = []
        init_hooks(self)

    def register_sdk_init_hook(self, hook: SDKInitHook) -> None:
        self.sdk_init_hooks.append(hook)

    def register_before_request_hook(self, hook: BeforeRequestHook) -> None:
        self.before_request_hooks.append(hook)

    def register_after_success_hook(self, hook: AfterSuccessHook) -> None:
        self.after_success_hooks.append(hook)

    def register_after_error_hook(self, hook: AfterErrorHook) -> None:
        self.after_error_hooks.append(hook)

    def sdk_init(self, base_url: str, client: Any) -> Tuple[str, Any]:
        for hook in self.sdk_init_hooks:
            base_url, client = hook.sdk_init(base_url, client)
        return base_url, client

    def before_request(self, hook_ctx: BeforeRequestContext, request: Any) -> Any:
        for hook in self.before_request_hooks:
            out = hook.before_request(hook_ctx, request)
            if isinstance(out, Exception):
                raise out
            request = out
        return request

    def after_success(self, hook_ctx: AfterSuccessContext, response: Any) -> Any:
        for hook in self.after_success_hooks:
            out = hook.after_success(hook_ctx, response)
            if isinstance(out, Exception):
                raise out
            response = out
        return response

    def after_error(
        self,
        hook_ctx: AfterErrorContext,
        response: Optional[Any],
        error: Optional[Exception],
    ) -> Tuple[Optional[Any], Optional[Exception]]:
        for hook in self.after_error_hooks:
            result = hook.after_error(hook_ctx, response, error)
            if isinstance(result, Exception):
                raise result
            response, error = result
        return response, error


def attach_hooks_to_api_client(
    api_client: Any,
    hooks: SDKHooks,
    base_url: str = "",
    security_source: Any = None,
    auth_headers: Optional[List[Tuple[str, str]]] = None,
) -> None:
    """Wrap api_client.call_api so registered hooks fire around each request.

    Notes:
      - operation_id is the real spec operation id (e.g. "create-company"),
        matching Speakeasy. Each generated method passes it to call_api as the
        operation_id keyword; it defaults to "<unknown>" only if a caller reaches
        call_api without going through a generated method. The value comes from
        the same source of truth the TypeScript arm uses (the x-codat-operation-id
        vendor extension, set in preprocess_oas.py).
      - The request and response objects are urllib3-flavoured, not httpx —
        consistent with our ApiClient. Hook authors should treat them opaquely.
      - security_source is the value passed to the SDK constructor. It may be a
        Security model or a zero-argument callable that returns one (Speakeasy's
        pattern for rotating credentials). It is resolved on every request so a
        rotating credential is picked up each time, and each (field, header) in
        auth_headers is set from the resolved value.
    """
    original_call_api = api_client.call_api
    resolved_auth_headers = auth_headers or []

    def apply_security(headers):
        if security_source is None or not resolved_auth_headers:
            return
        resolved = security_source() if callable(security_source) else security_source
        for field_name, header_name in resolved_auth_headers:
            value = getattr(resolved, field_name, None)
            if value is not None:
                headers[header_name] = value

    def wrapped(method, url, header_params=None, body=None, post_params=None, _request_timeout=None, operation_id="<unknown>"):
        headers = dict(header_params or {})
        apply_security(headers)
        hook_ctx = HookContext(
            config=None,
            base_url=base_url,
            operation_id=operation_id,
            oauth2_scopes=None,
            security_source=security_source,
        )
        request = {
            "method": method,
            "url": url,
            "headers": headers,
            "body": body,
            "post_params": post_params,
        }
        request = hooks.before_request(BeforeRequestContext(hook_ctx), request)
        try:
            response = original_call_api(
                method=request["method"],
                url=request["url"],
                header_params=request["headers"],
                body=request["body"],
                post_params=request.get("post_params"),
                _request_timeout=_request_timeout,
            )
        except Exception as e:
            new_response, new_error = hooks.after_error(AfterErrorContext(hook_ctx), None, e)
            if new_error is not None:
                raise new_error
            return new_response
        return hooks.after_success(AfterSuccessContext(hook_ctx), response)

    api_client.call_api = wrapped
