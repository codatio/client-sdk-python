"""Hooks abstract surface — mirrors Speakeasy's _hooks/types.py.

Generated by pipeline/postprocess_generated.py — do not edit by hand.

Class names and method signatures match Speakeasy bit-for-bit so SDK-author code
that registers hook implementations can be ported unchanged. The two deviations
from the Speakeasy SDK are intentional and documented in FEATURE-AUDIT.md:

  1. Request/response types are typed as Any here. Speakeasy uses httpx.Request /
     httpx.Response. Our OAG pipeline uses urllib3 via ApiClient, so we use Any
     to avoid forcing httpx as a transitive dependency. Hook implementations
     should treat the request and response parameters as opaque dicts/objects
     produced by ApiClient.
  2. HookContext.config is Any. Speakeasy ships an SDKConfiguration class; we
     do not.
"""

from abc import ABC, abstractmethod
from typing import Any, Callable, List, Optional, Tuple, Union


class HookContext:
    config: Any
    base_url: str
    operation_id: str
    oauth2_scopes: Optional[List[str]] = None
    security_source: Optional[Union[Any, Callable[[], Any]]] = None

    def __init__(
        self,
        config: Any,
        base_url: str,
        operation_id: str,
        oauth2_scopes: Optional[List[str]] = None,
        security_source: Optional[Union[Any, Callable[[], Any]]] = None,
    ) -> None:
        self.config = config
        self.base_url = base_url
        self.operation_id = operation_id
        self.oauth2_scopes = oauth2_scopes
        self.security_source = security_source


class BeforeRequestContext(HookContext):
    def __init__(self, hook_ctx: HookContext):
        super().__init__(
            hook_ctx.config,
            hook_ctx.base_url,
            hook_ctx.operation_id,
            hook_ctx.oauth2_scopes,
            hook_ctx.security_source,
        )


class AfterSuccessContext(HookContext):
    def __init__(self, hook_ctx: HookContext):
        super().__init__(
            hook_ctx.config,
            hook_ctx.base_url,
            hook_ctx.operation_id,
            hook_ctx.oauth2_scopes,
            hook_ctx.security_source,
        )


class AfterErrorContext(HookContext):
    def __init__(self, hook_ctx: HookContext):
        super().__init__(
            hook_ctx.config,
            hook_ctx.base_url,
            hook_ctx.operation_id,
            hook_ctx.oauth2_scopes,
            hook_ctx.security_source,
        )


class SDKInitHook(ABC):
    @abstractmethod
    def sdk_init(self, base_url: str, client: Any) -> Tuple[str, Any]:
        ...


class BeforeRequestHook(ABC):
    @abstractmethod
    def before_request(self, hook_ctx: BeforeRequestContext, request: Any) -> Union[Any, Exception]:
        ...


class AfterSuccessHook(ABC):
    @abstractmethod
    def after_success(self, hook_ctx: AfterSuccessContext, response: Any) -> Union[Any, Exception]:
        ...


class AfterErrorHook(ABC):
    @abstractmethod
    def after_error(
        self,
        hook_ctx: AfterErrorContext,
        response: Optional[Any],
        error: Optional[Exception],
    ) -> Union[Tuple[Optional[Any], Optional[Exception]], Exception]:
        ...


class Hooks(ABC):
    @abstractmethod
    def register_sdk_init_hook(self, hook: SDKInitHook) -> None:
        ...

    @abstractmethod
    def register_before_request_hook(self, hook: BeforeRequestHook) -> None:
        ...

    @abstractmethod
    def register_after_success_hook(self, hook: AfterSuccessHook) -> None:
        ...

    @abstractmethod
    def register_after_error_hook(self, hook: AfterErrorHook) -> None:
        ...
