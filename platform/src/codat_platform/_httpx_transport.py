"""Adapter that routes SDK requests through a consumer-passed httpx.Client.

Generated by pipeline/postprocess_generated.py — do not edit by hand.

Exposes the same request() surface as the generated urllib3 RESTClientObject,
so the consumer's proxies, TLS settings, and instrumentation apply to every
request (the Speakeasy SDK behaviour for the `client` constructor kwarg).
"""

import io
import json
import re

from .exceptions import ApiException, ApiValueError


class HttpxRestResponse(io.IOBase):

    def __init__(self, resp) -> None:
        self.response = resp
        self.status = resp.status_code
        self.reason = resp.reason_phrase
        self.data = None

    def read(self):
        if self.data is None:
            self.data = self.response.content
        return self.data

    def getheaders(self):
        """Returns the response headers (case-insensitive mapping)."""
        return self.response.headers

    def getheader(self, name, default=None):
        """Returns a given response header."""
        return self.response.headers.get(name, default)


def _to_httpx_timeout(request_timeout):
    """Map the generated stack's timeout (number or (connect, read) pair) onto
    an httpx.Timeout. None means: use the passed client's own default."""
    if request_timeout is None:
        return None
    import httpx

    if isinstance(request_timeout, (int, float)):
        return httpx.Timeout(request_timeout)
    connect, read = request_timeout
    return httpx.Timeout(read, connect=connect)


class HttpxRestClient:

    def __init__(self, client) -> None:
        self.client = client

    def request(
        self,
        method,
        url,
        headers=None,
        body=None,
        post_params=None,
        _request_timeout=None,
    ):
        method = method.upper()
        assert method in [
            "GET",
            "HEAD",
            "DELETE",
            "POST",
            "PUT",
            "PATCH",
            "OPTIONS",
        ]

        if post_params and body:
            raise ApiValueError(
                "body parameter cannot be used with post_params parameter."
            )

        post_params = post_params or []
        headers = dict(headers or {})

        content = None
        data = None
        files = None

        if method in ["POST", "PUT", "PATCH", "OPTIONS", "DELETE"]:
            content_type = headers.get("Content-Type")
            if not content_type or re.search("json", content_type, re.IGNORECASE):
                if body is not None:
                    content = json.dumps(body)
            elif content_type == "application/x-www-form-urlencoded":
                data = dict(post_params)
            elif content_type == "multipart/form-data":
                # httpx must set the Content-Type itself to carry the boundary.
                del headers["Content-Type"]
                data = {}
                files = []
                for name, value in post_params:
                    if isinstance(value, tuple) and len(value) == 3:
                        files.append((name, value))
                    elif isinstance(value, dict):
                        data[name] = json.dumps(value)
                    else:
                        data[name] = value
            elif isinstance(body, (str, bytes)):
                content = body
            elif content_type.startswith("text/") and isinstance(body, bool):
                content = "true" if body else "false"
            else:
                msg = """Cannot prepare a request message for provided
                         arguments. Please check that your arguments match
                         declared content type."""
                raise ApiException(status=0, reason=msg)

        request_kwargs = {"headers": headers}
        if content is not None:
            request_kwargs["content"] = content
        if data is not None:
            request_kwargs["data"] = data
        if files:
            request_kwargs["files"] = files
        timeout = _to_httpx_timeout(_request_timeout)
        if timeout is not None:
            request_kwargs["timeout"] = timeout

        resp = self.client.request(method, url, **request_kwargs)
        return HttpxRestResponse(resp)
